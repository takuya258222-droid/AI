/** メッセージ中の表示テキストを順に取り出す（設計書に本文として載せる用） */
function textsOf(msg) {
  const out = [];
  const walk = (o) => {
    if (Array.isArray(o)) return o.forEach(walk);
    if (o && typeof o === "object") {
      if (o.type === "text" && typeof o.text === "string") out.push(o.text);
      else if (o.type === "image" && o.url) out.push(`〔画像：${o.url.replace(BASE + "/img/", "")}〕`);
      if (o.type === "postback" || o.type === "uri") { /* ボタンは別途 */ }
      Object.values(o).forEach(walk);
    }
  };
  walk(msg.contents ?? msg);
  if (msg.type === "text") out.push(msg.text);
  return out;
}
function buttonsOf(msg) {
  const out = [];
  const walk = (o) => {
    if (Array.isArray(o)) return o.forEach(walk);
    if (o && typeof o === "object") {
      if (o.type === "postback") out.push(`【${o.displayText ?? o.label}】→ 内部動作 \`${o.data}\``);
      if (o.type === "uri") out.push(`【${o.label}】→ URLを開く（${o.uri.replace(BASE, "")}）`);
      Object.values(o).forEach(walk);
    }
  };
  walk(msg);
  return [...new Set(out)];
}
